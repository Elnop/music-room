/**
 * Helper: Find track by ID
 */
export const findTrackById = (id: string): Track | undefined => {
  return MOCK_TRACKS.find(track => track.id === id);
};

/**
 * Helper: Search tracks by query
 * Searches in title, artist, and album
 */
export const searchTracks = (query: string): Track[] => {
  if (!query || query.trim() === '') {
    return MOCK_TRACKS;
  }

  const lowerQuery = query.toLowerCase().trim();

  return MOCK_TRACKS.filter(
    track =>
      track.title.toLowerCase().includes(lowerQuery) ||
      track.artist.toLowerCase().includes(lowerQuery) ||
      track.album.toLowerCase().includes(lowerQuery)
  );
};

/**
 * Helper: Get tracks by IDs
 */
export const getTracksByIds = (trackIds: string[]): Track[] => {
  return trackIds
    .map(id => findTrackById(id))
    .filter((track): track is Track => track !== undefined);
};

/**
 * Helper: Get random tracks
 */
export const getRandomTracks = (count: number): Track[] => {
  const shuffled = [...MOCK_TRACKS].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
};
