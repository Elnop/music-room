#!/bin/sh
set -e

echo "=========================================="
echo "Starting Expo in Tunnel Mode"
echo "=========================================="
echo "Mode: Tunnel (cross-network development)"
echo "Port: 8081"
echo "=========================================="

# Wait for a live backend tunnel URL (max 60 seconds)
BACKEND_TUNNEL_URL=""
MAX_ATTEMPTS=12
ATTEMPT=0

echo "→ Waiting for backend tunnel to initialize..."
while [ $ATTEMPT -lt $MAX_ATTEMPTS ]; do
  if [ -f /tmp/shared/backend-tunnel-url.txt ]; then
    BACKEND_TUNNEL_URL=$(cat /tmp/shared/backend-tunnel-url.txt 2>/dev/null || true)

    # Accept the URL only once the backend answers through it: a file left by
    # a previous run, or by a backend that exited, points at a dead tunnel.
    if [ -n "$BACKEND_TUNNEL_URL" ] && node -e '
      fetch(process.argv[1] + "/health", { headers: { "ngrok-skip-browser-warning": "1" } })
        .then(r => process.exit(r.ok ? 0 : 1), () => process.exit(1));
    ' "$BACKEND_TUNNEL_URL"; then
      echo "✓ Backend tunnel URL found: $BACKEND_TUNNEL_URL"

      # Export backend tunnel URL for mobile app to use
      export EXPO_PUBLIC_API_URL="$BACKEND_TUNNEL_URL"
      # POSIX sh (dash in the image): no ${var/x/y} substitution.
      export EXPO_PUBLIC_WS_URL="$(printf '%s' "$BACKEND_TUNNEL_URL" | sed 's|^https|wss|')"

      echo "→ Mobile app will connect to:"
      echo "   API: $EXPO_PUBLIC_API_URL"
      echo "   WS:  $EXPO_PUBLIC_WS_URL"

      # In development Expo reads EXPO_PUBLIC_* from the .env files before the
      # environment; this file comes last in its priority order (git-ignored).
      printf '%s\n' \
        '# Generated by start-expo-tunnel.sh (dev-tunnel): backend the app calls.' \
        '# Expo gives this file priority over .env. Do not edit.' \
        "EXPO_PUBLIC_API_URL=$EXPO_PUBLIC_API_URL" \
        "EXPO_PUBLIC_WS_URL=$EXPO_PUBLIC_WS_URL" > .env.development.local
      break
    fi
  fi

  ATTEMPT=$((ATTEMPT + 1))
  if [ $ATTEMPT -lt $MAX_ATTEMPTS ]; then
    echo "   Waiting for backend tunnel... (attempt $ATTEMPT/$MAX_ATTEMPTS)"
    sleep 5
  fi
done

# If we exhausted all attempts, fail explicitly
if [ -z "$BACKEND_TUNNEL_URL" ]; then
  echo ""
  echo "❌ ERROR: no live backend tunnel URL after 60 seconds"
  echo ""
  echo "Debugging information:"
  echo "  Shared volume mount: $(ls -la /tmp/shared 2>/dev/null || echo 'NOT FOUND')"
  echo "  Backend tunnel file: $(ls -l /tmp/shared/backend-tunnel-url.txt 2>/dev/null || echo 'NOT FOUND')"
  echo ""
  echo "Possible causes:"
  echo "  1. Backend container not started or not in tunnel mode"
  echo "  2. ngrok failed to initialize (check: docker logs zumik-backend)"
  echo "  3. Shared volume not mounted correctly"
  echo "  4. Permission issues (files not readable by mobile container)"
  echo ""
  echo "To fix:"
  echo "  1. Check backend logs: docker logs zumik-backend"
  echo "  2. Verify backend container: docker ps"
  echo "  3. Check tunnel file: docker exec zumik-backend cat /tmp/shared/backend-tunnel-url.txt"
  echo "  4. Recreate the containers: docker rm -fv zumik-backend zumik-mobile && make dev-tunnel"
  echo ""
  exit 1
fi

# SUPABASE_MODE=local (#251): the phone reaches the local stack's auth API
# through the backend tunnel, which forwards /supabase/auth/v1/* to it (one
# ngrok endpoint on the free plan). Hosted mode keeps mobile/.env's project.
if [ "$SUPABASE_MODE" = "local" ]; then
  SUPABASE_PROXY_URL="$BACKEND_TUNNEL_URL/supabase"

  if [ -z "$SUPABASE_ANON_KEY" ]; then
    echo ""
    echo "❌ ERROR: SUPABASE_ANON_KEY not set in local Supabase mode"
    echo "   Start the dev stack first: make supabase-up (writes backend/.env.supabase.local)"
    echo "   Or use the hosted project: SUPABASE_MODE=hosted make dev-tunnel"
    echo ""
    exit 1
  fi

  echo "→ Waiting for the local Supabase stack through the backend tunnel..."
  SUPABASE_READY=false
  ATTEMPT=0
  while [ $ATTEMPT -lt $MAX_ATTEMPTS ]; do
    if node -e '
      fetch(process.argv[1] + "/auth/v1/health", {
        headers: { apikey: process.argv[2], "ngrok-skip-browser-warning": "1" },
      }).then(r => process.exit(r.ok ? 0 : 1), () => process.exit(1));
    ' "$SUPABASE_PROXY_URL" "$SUPABASE_ANON_KEY"; then
      SUPABASE_READY=true
      break
    fi

    ATTEMPT=$((ATTEMPT + 1))
    if [ $ATTEMPT -lt $MAX_ATTEMPTS ]; then
      echo "   Waiting for Supabase... (attempt $ATTEMPT/$MAX_ATTEMPTS)"
      sleep 5
    fi
  done

  if [ "$SUPABASE_READY" != "true" ]; then
    echo ""
    echo "❌ ERROR: local Supabase stack not reachable at $SUPABASE_PROXY_URL after 60 seconds"
    echo ""
    echo "Possible causes:"
    echo "  1. Dev stack stopped (check: make supabase-status, start: make supabase-up)"
    echo "  2. Backend not started with TUNNEL_MODE=true in development (check: docker logs zumik-backend)"
    echo ""
    exit 1
  fi
  echo "✓ Local Supabase reachable: $SUPABASE_PROXY_URL"

  # Exported too: mobile/.env's hosted values are already in the container's
  # environment, which Expo would otherwise prefer over the .env files.
  export EXPO_PUBLIC_SUPABASE_URL="$SUPABASE_PROXY_URL"
  export EXPO_PUBLIC_SUPABASE_ANON_KEY="$SUPABASE_ANON_KEY"
  printf '%s\n' \
    "EXPO_PUBLIC_SUPABASE_URL=$EXPO_PUBLIC_SUPABASE_URL" \
    "EXPO_PUBLIC_SUPABASE_ANON_KEY=$EXPO_PUBLIC_SUPABASE_ANON_KEY" >> .env.development.local
fi

echo "=========================================="
echo "Starting Expo Metro bundler with tunnel..."
echo "=========================================="
echo ""
echo "⚠️  Note: Tunnel mode requires EAS login"
echo "   If prompted, please login with your EAS account"
echo ""

# Start Expo with tunnel mode (cannot use --offline with --tunnel)
# @expo/ngrok is now installed locally, so no interactive prompt
# Force --host tunnel explicitly
# --dev-client: the app runs as the Zumik debug build, not in Expo Go
npx expo start --host tunnel --dev-client --port 8081

echo ""
echo "Expo tunnel stopped"
