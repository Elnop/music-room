#!/usr/bin/env sh
# Local Supabase stack and Redis for backend integration tests (see doc/development/testing.md).
#
#   scripts/test-db.sh up     start the stack, reset the database, apply
#                             migrations/*.sql in order, start a Redis
#                             container on a free port, write .env.test
#   scripts/test-db.sh down   stop the stack, drop its data, remove Redis
#
# Runs from backend/. Needs Docker. Ports are in supabase/config.toml (554xx,
# so the stack can run next to another local Supabase project).
set -eu

cd "$(dirname "$0")/.."

# The Supabase CLI reads backend/.env, where SUPABASE_PROJECT_ID names the
# hosted project; pin the local stack's name so containers never use it.
export SUPABASE_PROJECT_ID=music-room-test
DB_CONTAINER="supabase_db_${SUPABASE_PROJECT_ID}"

# Only Postgres, PostgREST, Auth, Storage (avatars bucket, #351) and Kong are
# needed by supabase-js.
EXCLUDED=studio,imgproxy,realtime,edge-runtime,logflare,vector,mailpit,supavisor,postgres-meta

# Real Redis (session revocation denylist); Docker picks a free host port.
# The official image through ECR Public, like the Supabase images: Docker Hub
# refuses anonymous pulls past its rate limit on shared CI runners.
REDIS_CONTAINER=music-room-test-redis
REDIS_IMAGE=public.ecr.aws/docker/library/redis:7-alpine

# ECR Public throttles bursts ("Rate exceeded"): retry with a growing delay.
pull_image() {
	tries=0
	until docker image inspect "$1" >/dev/null 2>&1 || docker pull -q "$1" >/dev/null; do
		tries=$((tries + 1))
		if [ "$tries" -ge 5 ]; then
			echo "Could not pull $1" >&2
			exit 1
		fi
		sleep $((tries * 5))
	done
}

start_redis() {
	docker rm -f "$REDIS_CONTAINER" >/dev/null 2>&1 || true
	pull_image "$REDIS_IMAGE"
	docker run -d --name "$REDIS_CONTAINER" -p 127.0.0.1::6379 "$REDIS_IMAGE" >/dev/null

	tries=0
	until docker exec "$REDIS_CONTAINER" redis-cli ping 2>/dev/null | grep -q PONG; do
		tries=$((tries + 1))
		if [ "$tries" -ge 30 ]; then
			echo "Redis did not start" >&2
			exit 1
		fi
		sleep 1
	done

	REDIS_PORT=$(docker port "$REDIS_CONTAINER" 6379/tcp | head -n 1 | sed 's/.*://')
}

up() {
	npx supabase start -x "$EXCLUDED" >/dev/null
	npx supabase db reset --local --no-seed >/dev/null

	for file in $(ls migrations/*.sql | sort); do
		if ! docker exec -i -e PGOPTIONS=--client-min-messages=warning "$DB_CONTAINER" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q <"$file" >/dev/null; then
			echo "Migration failed: $file" >&2
			exit 1
		fi
	done

	# PostgREST caches the schema; reload it after the migrations.
	docker exec "$DB_CONTAINER" psql -U postgres -d postgres -qc "NOTIFY pgrst, 'reload schema';" >/dev/null

	start_redis

	status=$(npx supabase status -o env 2>/dev/null)
	value() { printf '%s\n' "$status" | sed -n "s/^$1=\"\(.*\)\"$/\1/p"; }

	cat >.env.test <<EOF
# Generated by scripts/test-db.sh up; local-only keys, do not commit.
SUPABASE_URL=$(value API_URL)
SUPABASE_ANON_KEY=$(value ANON_KEY)
SUPABASE_SERVICE_KEY=$(value SERVICE_ROLE_KEY)
REDIS_HOST=127.0.0.1
REDIS_PORT=$REDIS_PORT
REDIS_PASSWORD=
REDIS_DB=0
EOF
	echo "Local Supabase ready on $(value API_URL), Redis on 127.0.0.1:$REDIS_PORT; wrote .env.test"
}

down() {
	docker rm -f "$REDIS_CONTAINER" >/dev/null 2>&1 || true
	npx supabase stop --no-backup
}

case "${1:-}" in
up) up ;;
down) down ;;
*)
	echo "Usage: $0 up|down" >&2
	exit 2
	;;
esac
