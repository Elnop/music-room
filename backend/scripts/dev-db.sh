#!/usr/bin/env sh
# Local Supabase stack for development (SUPABASE_MODE=local, see backend/README.md).
# Unlike scripts/test-db.sh, it keeps its data between runs.
#
#   scripts/dev-db.sh up      start the stack, apply the backend/migrations files
#                             not applied yet, write .env.supabase.local
#   scripts/dev-db.sh down    stop the stack, keep its data
#   scripts/dev-db.sh reset   empty the database, apply every migration again
#
# Runs from backend/. Needs Docker. The CLI workdir is supabase-dev/ (config in
# supabase-dev/supabase/config.toml, ports 544xx), so this stack never shares
# a container, a volume or a port with the test stack (backend/supabase, 554xx).
set -eu

cd "$(dirname "$0")/.."

CLI=node_modules/.bin/supabase
WORKDIR=supabase-dev
ENV_FILE=.env.supabase.local

# Pin the stack's name: backend/.env sets SUPABASE_PROJECT_ID to the hosted
# project, and the CLI would name the containers after it.
export SUPABASE_PROJECT_ID=music-room-dev
DB_CONTAINER="supabase_db_${SUPABASE_PROJECT_ID}"
API_PORT=54421
SMTP_PORT=54425
MAIL_UI_PORT=54424

# supabase-js needs Postgres, PostgREST, Auth and Kong (as in test-db.sh); Mailpit
# catches the backend's emails (web UI on $MAIL_UI_PORT).
EXCLUDED=studio,storage-api,imgproxy,realtime,edge-runtime,logflare,vector,supavisor,postgres-meta

# Migrations already applied, one row per file name. Outside `public`, so
# PostgREST never exposes it and the generated types never list it.
TRACKING=zumik_dev.applied_migrations

fail() {
	echo "$1" >&2
	exit 1
}

check_tools() {
	command -v docker >/dev/null 2>&1 || fail "Docker is not installed: https://docs.docker.com/get-docker/"
	docker info >/dev/null 2>&1 || fail "Docker is not running (or this user cannot reach it): start Docker and retry"
	[ -x "$CLI" ] || fail "Supabase CLI not found in backend/node_modules: run make install"
}

# The [auth.external.*] blocks of config.toml read these through env(). Only
# these keys are read, so the rest of backend/.env never reaches a shell.
load_oauth_env() {
	for key in GOOGLE_CLIENT_ID FACEBOOK_APP_ID FACEBOOK_APP_SECRET; do
		value=""
		if [ -f .env ]; then
			value=$(sed -n "s/^${key}=//p" .env | tail -n 1 | sed -e 's/[[:space:]]#.*$//' -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/")
		fi
		export "$key=$value"
	done
}

host_ip() {
	if [ -n "${HOST_IP:-}" ] && [ "$HOST_IP" != "0.0.0.0" ]; then
		echo "$HOST_IP"
		return
	fi
	ip=$(ip route get 1 2>/dev/null | awk '{print $7; exit}') || true
	[ -n "$ip" ] || ip=$(ipconfig getifaddr en0 2>/dev/null) || true
	echo "${ip:-127.0.0.1}"
}

psql_db() {
	docker exec -i -e PGOPTIONS=--client-min-messages=warning "$DB_CONTAINER" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q "$@"
}

# Apply, in file order, each migration with no row in $TRACKING. Each file runs
# in one transaction with its row, so a failing file leaves no trace.
apply_migrations() {
	psql_db -c "CREATE SCHEMA IF NOT EXISTS zumik_dev; CREATE TABLE IF NOT EXISTS $TRACKING (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());" >/dev/null
	applied=$(psql_db -tAc "SELECT name FROM $TRACKING")

	count=0
	for file in $(ls migrations/*.sql | sort); do
		name=$(basename "$file")
		if printf '%s\n' "$applied" | grep -qxF "$name"; then
			continue
		fi
		if ! { cat "$file"; printf "\nINSERT INTO %s (name) VALUES ('%s');\n" "$TRACKING" "$name"; } | psql_db -1 -f - >/dev/null; then
			fail "Migration failed: $file (nothing from it was applied)"
		fi
		echo "Applied $name"
		count=$((count + 1))
	done

	# PostgREST caches the schema; reload it after the migrations.
	psql_db -c "NOTIFY pgrst, 'reload schema';" >/dev/null
	echo "$count migration(s) applied"
}

write_env_file() {
	status=$("$CLI" status -o env --workdir "$WORKDIR" 2>/dev/null)
	value() { printf '%s\n' "$status" | sed -n "s/^$1=\"\(.*\)\"$/\1/p"; }

	anon=$(value ANON_KEY)
	service=$(value SERVICE_ROLE_KEY)
	[ -n "$anon" ] && [ -n "$service" ] || fail "Could not read the stack's keys from supabase status"

	# The backend container and the phone reach the stack through the host's
	# LAN address; make dev-local swaps it for localhost, make dev-docker for
	# host.docker.internal.
	cat >"$ENV_FILE" <<EOF
# Generated by scripts/dev-db.sh (make supabase-up); local-only keys, do not commit.
SUPABASE_URL=http://$(host_ip):$API_PORT
SUPABASE_ANON_KEY=$anon
SUPABASE_SERVICE_KEY=$service
SMTP_HOST=$(host_ip)
SMTP_PORT=$SMTP_PORT
EOF
}

up() {
	check_tools
	# CLI output shown: the first run pulls the images for a few minutes.
	load_oauth_env
	"$CLI" start --workdir "$WORKDIR" -x "$EXCLUDED"
	apply_migrations
	write_env_file
	echo "Dev Supabase ready on http://127.0.0.1:$API_PORT, emails on http://127.0.0.1:$MAIL_UI_PORT; wrote backend/$ENV_FILE"
}

down() {
	check_tools
	"$CLI" stop --workdir "$WORKDIR"
}

reset() {
	check_tools
	load_oauth_env
	"$CLI" start --workdir "$WORKDIR" -x "$EXCLUDED"
	"$CLI" db reset --local --no-seed --workdir "$WORKDIR" >/dev/null
	apply_migrations
	write_env_file
	echo "Dev Supabase reset on http://127.0.0.1:$API_PORT; wrote backend/$ENV_FILE"
}

case "${1:-}" in
up) up ;;
down) down ;;
reset) reset ;;
*)
	echo "Usage: $0 up|down|reset" >&2
	exit 2
	;;
esac
