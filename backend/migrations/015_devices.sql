-- Zumik - Devices and per-device music control licenses (subject IV.2.2)
-- A user's devices are recorded when they connect; the user grants control of
-- each device separately to a friend. follows.can_control_music stays as the
-- "all my devices" shortcut.

-- =====================================================
-- Devices Table
-- =====================================================
-- One row per (user, deviceId). The deviceId is generated and persisted by the
-- app (AsyncStorage), so two accounts used on the same phone get two rows.

CREATE TABLE IF NOT EXISTS public.devices (
  user_id UUID NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL CHECK (char_length(device_id) BETWEEN 1 AND 128),
  device_name TEXT NOT NULL DEFAULT '',
  platform TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, device_id)
);

-- =====================================================
-- Device Control Licenses Table
-- =====================================================
-- owner_id lets grantee_id control the owner's device device_id.
-- The grantee must follow the owner: the foreign key to follows drops the
-- license when that follow is removed. follows(B, A) is the same row that
-- carries A's "all my devices" switch for B (009_music_control.sql).

CREATE TABLE IF NOT EXISTS public.device_control_licenses (
  owner_id UUID NOT NULL,
  device_id TEXT NOT NULL,
  grantee_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (owner_id, device_id, grantee_id),
  CONSTRAINT device_control_licenses_device_fkey
    FOREIGN KEY (owner_id, device_id)
    REFERENCES public.devices(user_id, device_id) ON DELETE CASCADE,
  CONSTRAINT device_control_licenses_follow_fkey
    FOREIGN KEY (grantee_id, owner_id)
    REFERENCES public.follows(follower_id, following_id) ON DELETE CASCADE,
  CONSTRAINT no_self_license CHECK (owner_id != grantee_id)
);

-- "Which devices of this owner can I control" and the follows foreign key
CREATE INDEX IF NOT EXISTS idx_device_control_licenses_grantee
  ON public.device_control_licenses(grantee_id, owner_id);

-- =====================================================
-- Row Level Security (RLS) Policies
-- =====================================================
-- The backend uses the service role; these policies only bound direct access.

ALTER TABLE public.devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.device_control_licenses ENABLE ROW LEVEL SECURITY;

-- Policy: Users manage only their own devices
CREATE POLICY "devices_select_policy"
  ON public.devices
  FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "devices_insert_policy"
  ON public.devices
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "devices_update_policy"
  ON public.devices
  FOR UPDATE
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "devices_delete_policy"
  ON public.devices
  FOR DELETE
  USING (auth.uid() = user_id);

-- Policy: The owner and the grantee can view a license
CREATE POLICY "device_control_licenses_select_policy"
  ON public.device_control_licenses
  FOR SELECT
  USING (auth.uid() = owner_id OR auth.uid() = grantee_id);

-- Policy: Only the owner grants or revokes
CREATE POLICY "device_control_licenses_insert_policy"
  ON public.device_control_licenses
  FOR INSERT
  WITH CHECK (auth.uid() = owner_id);

CREATE POLICY "device_control_licenses_delete_policy"
  ON public.device_control_licenses
  FOR DELETE
  USING (auth.uid() = owner_id);

-- =====================================================
-- Comments for documentation
-- =====================================================

COMMENT ON TABLE public.devices IS 'Devices a user has connected from, keyed by the deviceId the app persists.';
COMMENT ON COLUMN public.devices.device_id IS 'Stable id generated by the app (Socket.io handshake deviceId)';
COMMENT ON COLUMN public.devices.last_seen_at IS 'Last authenticated connection from this device';

COMMENT ON TABLE public.device_control_licenses IS 'Per-device music control: owner_id lets grantee_id control device device_id.';

COMMENT ON COLUMN public.follows.can_control_music IS
  'If true, the follower (follower_id) can control the music of following_id on all of its devices.
   Per-device grants are in device_control_licenses.
   Example: In follows(B, A) with can_control_music=true, A authorizes B to control all their devices.';
